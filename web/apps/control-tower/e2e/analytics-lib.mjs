function instrument(page) {
  page.requests = [];
  page.consoleErrors = [];
  page.urls = [];
  page.on("request", (r) => page.requests.push({ method: r.method(), url: r.url(), at: Date.now() }));
  page.on("console", (m) => {
    if (m.type() === "error") page.consoleErrors.push(`${m.text()}${m.location()?.url ? ` (${m.location().url})` : ""}`);
  });
  page.on("pageerror", (e) => page.consoleErrors.push(`pageerror: ${e.message}`));
  page.on("framenavigated", (f) => {
    if (f === page.mainFrame()) page.urls.push(f.url());
  });
}

