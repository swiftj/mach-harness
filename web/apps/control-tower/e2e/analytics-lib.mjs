/** Every figure in the sheet: name, summary, chart id, a Table toggle, and whether it shows a reason instead. */
export async function readFigures(page) {
  return page.evaluate(() => {
    const main = [...document.querySelectorAll("main[aria-label]")].pop();
    return [...(main?.querySelectorAll("figure") ?? [])].map((f) => {
      const byIds = (attr) =>
        (f.getAttribute(attr) ?? "")
          .split(/\s+/)
          .filter(Boolean)
          .map((id) => document.getElementById(id)?.textContent ?? "")
          .join(" ")
          .trim();
      const heading = f.querySelector("h1,h2,h3,h4")?.textContent?.trim() ?? "";
      return {
        id: f.getAttribute("data-chart") ?? f.id ?? null,
        name: byIds("aria-labelledby") || f.getAttribute("aria-label") || heading,
        heading,
        summary: byIds("aria-describedby"),
        // A Table/Chart toggle, or the figure is itself a table.
        table: [...f.querySelectorAll("button")].some((b) => /^(Table|Chart)$/.test(b.textContent.trim())) || Boolean(f.querySelector("table")),
        missing: f.querySelector("[data-state]")?.getAttribute("data-state") ?? null,
        drawn: Boolean(f.querySelector("svg, canvas")),
        text: f.textContent.replace(/\s+/g, " ").trim().slice(0, 300),
      };
    });
  });
}

