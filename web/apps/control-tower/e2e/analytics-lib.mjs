// audit (scripts/analytics-audit.mjs) and its performance measurement (scripts/analytics-measure.mjs).
// docs/mach-next/M6_5_TESTING.md describes all three.
//
// Two modes, one set of helpers:
//   proof  the areas' development proof page (/src/analytics/dev/proof.html) on the seeded, simulated
//          fixture, and the Shell's #analytics over the built-in Simulation. Needs only the dev server.
//   live   mach-observer built from this working tree with plain `go build` (never build.sh), on a
//          project generated by `mach-synth --analytics` into the scratch folder, and the Shell's
