/** `go build` mach-observer and mach-synth from the working tree into the scratch folder (never build.sh). */
export function buildTools() {
  mkdirSync(dirname(bin.observer), { recursive: true });
  const notes = [];
  for (const [out, pkg] of [
    [bin.observer, "./cmd/mach-observer"],
    [bin.synth, "./internal/testkit/cmd/mach-synth"],
  ]) {
    const r = spawnSync("go", ["build", "-o", out, pkg], { cwd: observerSrc, encoding: "utf8" });
    if (r.status !== 0) {
      if (!existsSync(out)) throw new Error(`go build ${pkg} failed:\n${r.stderr.slice(0, 2000)}`);
      notes.push(`${pkg}: the working tree did not compile; using the previous build in ${out}`);
    } else notes.push(`built ${out}`);
  }
  return notes;
}

