/** The workspace is up: its sheet (or a designed empty state) on screen, then `data-analytics-ready` when the build sets it. */
export async function analyticsReady(page, timeout = 30000) {
  await page.waitForSelector(`${SEL.root}`, { timeout, state: "attached" });
  await page.waitForFunction(
    (sel) => {
      const root = document.querySelector(sel);
      if (!root) return false;
      return Boolean(root.querySelector("main[aria-label], [data-analytics-home] h2, [data-analytics-home] [role=status]")) || /not connected|No observer/i.test(root.textContent ?? "");
    },
    SEL.root,
    { timeout },
  );
  // The ready hook, where the build has it; a short settle where it does not.
  const has = await page.evaluate(() => document.querySelector("[data-analytics-ready]") !== null || document.querySelector("[data-analytics-workspace]")?.hasAttribute("data-analytics-pending"));
  if (has) await page.waitForSelector("[data-analytics-ready]", { timeout, state: "attached" }).catch(() => {});
  else await sleep(700);
  // The live workspace marks a view still loading with data-analytics-pending.
  await page.waitForFunction(() => !document.querySelector("[data-analytics-pending]"), undefined, { timeout }).catch(() => {});
}

