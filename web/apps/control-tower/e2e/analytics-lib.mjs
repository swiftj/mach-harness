/**
 * The synthetic projects, generated by this suite (never copied from elsewhere):
 *   empty   a project with `.factory/config.json` and nothing recorded
 *   one     one cell, one wave: a single finished run
 *   tiny    2 cells, 1 wave          (testdata/generate.sh: the same commands)
 *   medium  60 cells, 8 waves
 *   large   330 cells, 40 waves, 240,000 events
 * Returns { dir, summary } (summary null for `empty`). Regenerated unless `reuse` and present.
 */
export const PROJECTS = {
  one: ["--cells", "1", "--waves", "1", "--seed", "3"],
  tiny: ["--cells", "2", "--waves", "1", "--seed", "1"],
  medium: ["--cells", "60", "--waves", "8", "--seed", "1"],
  large: ["--cells", "330", "--waves", "40", "--events", "240000", "--seed", "1"],
};

export function makeProject(kind, { reuse = false, name = kind } = {}) {
  const dir = join(scratch, "projects", name);
  const summaryFile = join(dir, "synth-summary.json");
  if (kind === "empty") {
    rmSync(dir, { recursive: true, force: true });
    mkdirSync(join(dir, ".factory"), { recursive: true });
    writeFileSync(join(dir, ".factory", "config.json"), "{}\n");
    return { dir, summary: null };
  }
  if (!PROJECTS[kind]) throw new Error(`no project kind ${kind}`);
  if (!(reuse && existsSync(summaryFile))) {
    rmSync(dir, { recursive: true, force: true });
    mkdirSync(dirname(dir), { recursive: true });
    const r = spawnSync(bin.synth, ["--out", dir, "--analytics", ...PROJECTS[kind]], { encoding: "utf8", maxBuffer: 64 << 20 });
    if (r.status !== 0) throw new Error(`mach-synth --analytics ${kind} failed: ${r.stderr}`);
  } else rmSync(join(dir, ".factory", "local", "observer"), { recursive: true, force: true });
  return { dir, summary: JSON.parse(readFileSync(summaryFile, "utf8")) };
}

/** Extend a generated project's open execution (mach-synth --append), in the background. */
export function startAppender(dir, { rate = 200, duration = "15s" } = {}) {
  const child = spawn(bin.synth, ["--out", dir, "--append", "--rate", String(rate), "--duration", duration], { stdio: ["ignore", "pipe", "pipe"], detached: true });
  registerPid(child.pid, "mach-synth --append");
  let out = "";
  child.stdout.on("data", (d) => (out += d));
  child.stderr.on("data", (d) => (out += d));
  return { child, done: new Promise((ok) => child.once("exit", (code) => ok({ code, out }))) };
}

// ------------------------------------------------------------ the observer

export async function startObserver(project, port, { timeoutMs = 120000, binary = bin.observer } = {}) {
  const linkFile = join(project, ".factory", "local", "observer", "link");
  const before = existsSync(linkFile) ? statSync(linkFile).mtimeMs : 0;
  mkdirSync(join(scratch, "logs"), { recursive: true });
  const logFile = join(scratch, "logs", `observer-${port}-${Date.now()}.log`);
  const fd = openSync(logFile, "a");
  const started = Date.now();
  const child = spawn(binary, ["--project", project, "--port", String(port)], { stdio: ["ignore", fd, fd], detached: true });
  closeSync(fd);
  child.unref();
  registerPid(child.pid, `mach-observer :${port}`);
  const output = () => (existsSync(logFile) ? readFileSync(logFile, "utf8") : "");
  const until = started + timeoutMs;
  while (Date.now() < until) {
    if (/^Open: /m.test(output()) && existsSync(linkFile) && statSync(linkFile).mtimeMs !== before) break;
    if (child.exitCode !== null) throw new Error(`mach-observer exited (${child.exitCode}):\n${output().slice(0, 3000)}`);
    await sleep(100);
  }
  if (!existsSync(linkFile)) throw new Error(`mach-observer wrote no link in ${timeoutMs} ms:\n${output().slice(0, 3000)}`);
  writeFileSync(TARGET, String(port));
  log("observer", port, "pid", child.pid, "on", project);
  return {
    port,
    pid: child.pid,
    project,
    started,
    origin: `http://${HOST}:${port}`,
    output,
    /** The one-time link, read immediately before use (each works once). */
    link: () => readFileSync(linkFile, "utf8").trim(),
    /** Point the relay (and so the dev server's /api) at this observer. */
    target: () => writeFileSync(TARGET, String(port)),
    stop: () =>
      new Promise((ok) => {
        if (child.exitCode !== null) return ok(child.exitCode);
        const t = setTimeout(() => {
          try {
            process.kill(child.pid, "SIGKILL");
          } catch {
            /* gone */
          }
        }, 5000);
        child.once("exit", (code) => {
          clearTimeout(t);
          ok(code);
        });
        child.kill("SIGTERM");
      }),
  };
}

/** A session cookie from a fresh one-time link, for GETs outside the browser. */
export async function apiSession(obs) {
  const res = await fetch(obs.link(), { redirect: "manual" });
  const set = res.headers.getSetCookie?.() ?? [];
  if (!set.length) throw new Error(`the link set no session cookie (status ${res.status})`);
  return set.map((c) => c.split(";")[0]).join("; ");
}

export async function apiGet(obs, cookie, path) {
  const t0 = performance.now();
  const res = await fetch(`${obs.origin}${path}`, { headers: { cookie } });
  const text = await res.text();
  const ms = performance.now() - t0;
  let body = null;
  try {
    body = JSON.parse(text);
  } catch {
    body = { raw: text.slice(0, 300) };
  }
  return { status: res.status, body, data: body?.data ?? null, ms, bytes: text.length };
}

export async function waitCaughtUp(obs, cookie, timeoutMs = 600000) {
  const until = Date.now() + timeoutMs;
  let last = null;
  while (Date.now() < until) {
    try {
      last = (await apiGet(obs, cookie, "/api/v1/health")).data;
      const f = last?.freshness ?? {};
      if (f.ingest?.catching_up === false && (f.projection?.lag_events ?? 0) === 0) return last;
    } catch {
      /* not answering yet */
    }
    await sleep(300);
  }
  throw new Error(`observer did not catch up: ${JSON.stringify(last).slice(0, 500)}`);
}

/** Which /api/v1/analytics routes this observer serves (a 404 "no such route" means not built yet). */
export async function analyticsRoutes(obs, cookie) {
  const out = {};
  for (const r of ["metrics", "flow", "contributors", "runs", "insights"]) {
    const q = r === "contributors" ? "?metric=C1" : r === "metrics" ? "?ids=T1" : "";
    const g = await apiGet(obs, cookie, `/api/v1/analytics/${r}${q}`);
    out[r] = g.status === 200 ? "ok" : `${g.status} ${g.body?.error?.message ?? ""}`.trim();
  }
  return out;
}

// ------------------------------------------------------------ dev server and relay

/** Forwards /api/... to the observer named in <scratch>/relay-target, with its own Host and Origin. */
export function startRelay(port = RELAY_PORT) {
  const server = createServer((req, res) => {
    const target = Number(existsSync(TARGET) ? readFileSync(TARGET, "utf8").trim() : 0);
    if (!target) {
      res.writeHead(502).end("no observer");
      return;
    }
    const headers = { ...req.headers, host: `${HOST}:${target}` };
    if (headers.origin) headers.origin = `http://${HOST}:${target}`;
    const up = httpRequest({ host: HOST, port: target, path: req.url, method: req.method, headers }, (r) => {
      res.writeHead(r.statusCode ?? 502, r.headers);
      r.pipe(res);
    });
    up.on("error", () => {
      if (!res.headersSent) res.writeHead(502);
      res.end();
    });
    res.on("close", () => up.destroy());
    req.pipe(up);
  });
  return new Promise((ok, fail) => server.once("error", fail).listen(port, HOST, () => ok(server)));
}

export async function spawnRelay() {
  if (await answers(`http://${HOST}:${RELAY_PORT}/`)) return;
  const child = spawn(process.execPath, [fileURLToPath(import.meta.url), "--relay"], { stdio: "ignore", detached: true });
  child.unref();
  registerPid(child.pid, `relay :${RELAY_PORT}`);
  for (let i = 0; i < 50 && !(await answers(`http://${HOST}:${RELAY_PORT}/`)); i++) await sleep(100);
}

/** Vite on DEV_PORT, proxying /api to the relay. Reused when it already answers. */
export async function spawnDevServer() {
  if (await answers(`${DEV_ORIGIN}/`)) return;
  const child = spawn(join(app, "node_modules", ".bin", "vite"), ["--port", String(DEV_PORT), "--strictPort", "--host", HOST], {
    cwd: app,
    stdio: ["ignore", "ignore", "ignore"],
    detached: true,
    env: { ...process.env, MACH_OBSERVER_PORT: String(RELAY_PORT) },
  });
  child.unref();
  registerPid(child.pid, `vite :${DEV_PORT}`);
  for (let i = 0; i < 160 && !(await answers(`${DEV_ORIGIN}/`)); i++) await sleep(250);
  if (!(await answers(`${DEV_ORIGIN}/`))) throw new Error(`the dev server did not answer on ${DEV_ORIGIN}`);
  log("dev server on", DEV_ORIGIN, "pid", child.pid);
}

/**
 * One run at a time: ports 4430-4439 and the scratch folder are shared, so a second run would kill the
 * first one's observers and regenerate its projects. The lock names the process holding it; a lock
 * whose process is gone is taken over. The global setup takes it for its child test processes.
 */
const LOCK = join(scratch, "run.lock");
export function takeLock(label) {
  if (process.env.E2E_AN_LOCKED === "1") return;
  if (existsSync(LOCK)) {
    const [pid, ...rest] = readFileSync(LOCK, "utf8").trim().split(" ");
    let alive = false;
    try {
      process.kill(Number(pid), 0);
      alive = Number(pid) !== process.pid;
    } catch {
      alive = false;
    }
    if (alive) throw new Error(`another analytics harness run (pid ${pid}: ${rest.join(" ")}) holds ports 4430-4439 and ${scratch}; wait for it, or set E2E_AN_SCRATCH and the E2E_AN_*_PORT variables`);
  }
  writeFileSync(LOCK, `${process.pid} ${label}\n`);
  process.env.E2E_AN_LOCKED = "1";
  process.once("exit", () => {
    try {
      if (readFileSync(LOCK, "utf8").startsWith(`${process.pid} `)) rmSync(LOCK, { force: true });
    } catch {
      /* gone */
    }
  });
}

/** Relay and dev server, plus the tools when live mode needs them. */
export async function ensureStack({ tools = false } = {}) {
  takeLock(process.argv[1] ?? "analytics harness");
  if (tools && (!existsSync(bin.observer) || !existsSync(bin.synth))) for (const n of buildTools()) log(n);
  await spawnRelay();
  await spawnDevServer();
}

