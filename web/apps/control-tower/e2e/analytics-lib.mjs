// ------------------------------------------------------------ processes

export function registerPid(pid, label) {
  appendFileSync(PIDS, `${pid} ${label}\n`);
  own.push(pid);
}

function killPid(pid) {
  for (const p of [-pid, pid]) {
    try {
      process.kill(p, "SIGTERM");
      return true;
    } catch {
      /* not a group, or gone */
    }
  }
  return false;
}

/** Kill every process any file of this suite recorded (the global teardown; safe to call twice). */
export function killRegistered() {
  if (!existsSync(PIDS)) return [];
  const killed = [];
  for (const line of readFileSync(PIDS, "utf8").split("\n")) {
    const [pid, ...label] = line.trim().split(" ");
    if (pid && killPid(Number(pid))) killed.push(`${pid} ${label.join(" ")}`);
  }
  rmSync(PIDS, { force: true });
  return killed;
}

/** Kill the processes this process started (a file run without the global setup). */
export function stopOwn() {
  if (process.env.E2E_AN_GLOBAL === "1") return [];
  const out = own.splice(0).filter(killPid);
  return out;
}

async function answers(url, ms = 1500) {
  try {
    const r = await fetch(url, { signal: AbortSignal.timeout(ms) });
    return r.status < 500;
  } catch {
    return false;
  }
}

